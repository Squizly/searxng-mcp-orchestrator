SEARCH_ROUTE_PROMPT = """Ты роутер для поискового агента.
Запрос пользователя: "{user_input}"

Правила:
- use_search=false, если это базовое объяснение или общая справка, которую можно дать из стабильных знаний:
  примеры: "что такое ...", "объясни простыми словами ...", "как работает ...", идеи, перефразирование, помощь с кодом.
- use_search=true, если нужны актуальные/проверяемые данные из внешних источников:
  новости, цены, версии, статистика, "сегодня/в этом году", сравнение с факт-чекингом, просьба дать ссылки.
- Если вопрос про общую концепцию без требования свежести данных, предпочитай use_search=false.
- Если пользователь явно просит "проверь в интернете/дай источники", всегда use_search=true.
- Если остаются сомнения, выбирай use_search=true.
- Верни только JSON:
{{
  "use_search": true/false
}}
Никаких комментариев вне JSON.
"""

DIRECT_ANSWER_PROMPT = """Ответь на запрос пользователя без веб-поиска.
Запрос: "{query}"

Требования:
- Дай прямой, полезный и структурированный ответ.
- Для вопроса вида "что такое X" начни с четкого определения X в первом предложении.
- Затем кратко раскрой: назначение, как это работает, где применяется (если уместно).
- Пиши конкретно, без канцелярита и без общих фраз-заглушек.
- Если уверенность низкая по отдельным деталям, явно пометь это в 1 коротком предложении.
- Пиши на языке запроса.
"""

SUMMARY_PROMPT = """Ты суммируешь результаты веб-поиска.
Запрос пользователя: "{query}"

Результаты:
{results}

Требования к ответу:
- Используй только факты из результатов, не выдумывай.
- Делай best-effort: даже если текст шумный (markdown/таблицы/мусор), извлеки полезные факты и сформируй ответ.
- Для вопроса вида "что такое X" в первом предложении дай четкое определение X.
- Затем кратко добавь: назначение/ключевые возможности/кто и где использует.
- Если данных частично не хватает, все равно дай максимально полезный ответ и явно укажи, чего не хватает.
- Не отвечай фразой "Результаты не соответствуют запросу", если есть хотя бы частично релевантные факты.
- Не перечисляй каждый результат по отдельности — дай связный текст.
- Пиши на языке запроса, без смеси языков.
- Пиши грамотно, без орфографических ошибок.
- Ответ: 4-8 предложений, до ~1400 символов.
- Не добавляй список источников — он будет добавлен отдельно.
"""


def build_search_route_prompt(user_input: str) -> str:
    return SEARCH_ROUTE_PROMPT.format(user_input=user_input)


def build_direct_answer_prompt(query: str) -> str:
    return DIRECT_ANSWER_PROMPT.format(query=query)


def build_summary_prompt(query: str, results: str) -> str:
    return SUMMARY_PROMPT.format(query=query, results=results)
